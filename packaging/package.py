def compile_iss(p):
    # The antivirus sometimes holds the new exe while ISCC writes its resources ("EndUpdateResource
    # failed"): try again after a pause.
    for attempt in range(4):
        r = subprocess.run([str(ISCC), "/Q", str(p)], capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode == 0:
            return
        if "EndUpdateResource" not in r.stdout + r.stderr:
            break
        time.sleep(5 * (attempt + 1))
    raise SystemExit(f"ISCC failed for {p.name}:\n{r.stdout}\n{r.stderr}")


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="1.0.0")
    ap.add_argument("--skip-installers", action="store_true")
    ap.add_argument("--dist", help="output folder (default dist/; its zips and installers are replaced)")
    a = ap.parse_args()
    global DIST, STAGE
    if a.dist:
        DIST = Path(a.dist).resolve()
        STAGE = DIST / "stage"
    DIST.mkdir(parents=True, exist_ok=True)
    for old in list(DIST.glob("*.zip")) + list(DIST.glob("*.exe")):
        old.unlink()
    staged = []
    for app in APPS + [LAUNCHER]:
        d = stage(app, a.version)
        staged.append((app, d))
        z = portable_zip(app, a.version, d)
        print(f"{app[2]:10s} {z.name} {z.stat().st_size / 1e6:.1f} MB")
        if not a.skip_installers:
            compile_iss(iss_app(app, a.version, d))
    if not a.skip_installers:
        # launcher first in the suite: it is the hub and always installed
        compile_iss(iss_suite(a.version, [s for s in staged if s[0][0] == "warsha"] + [s for s in staged if s[0][0] != "warsha"]))
    files = sorted(list(DIST.glob("*.zip")) + list(DIST.glob("*.exe")))
    lines = [f"{sha256(f)}  {f.name}" for f in files]
    # LF endings, so `sha256sum -c` reads it on Linux and macOS too
    (DIST / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for f in files:
        print(f"{f.stat().st_size / 1e6:8.1f} MB  {f.name}")


if __name__ == "__main__":
    main()
